-- Question 38
-- Find the month-over-month growth in sales for 2023.
SELECT 
    m1.Month,
    m1.Total_Sales,
    ROUND(
        (m1.Total_Sales - m2.Total_Sales) / m2.Total_Sales * 100,
        2
    ) AS MoM_Growth_Percent
FROM
(
    SELECT 
        MONTH(Order_Date) AS Month,
        SUM(Total_Amount) AS Total_Sales
    FROM Orders
    WHERE YEAR(Order_Date) = 2023
    GROUP BY MONTH(Order_Date)
) m1
JOIN
(
    SELECT 
        MONTH(Order_Date) AS Month,
        SUM(Total_Amount) AS Total_Sales
    FROM Orders
    WHERE YEAR(Order_Date) = 2023
    GROUP BY MONTH(Order_Date)
) m2
ON m1.Month = m2.Month + 1;
