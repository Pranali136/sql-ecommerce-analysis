-- Question 49
-- Find the median salary for each department.
WITH RankedSalaries AS (
    SELECT 
        Department,
        Salary,
        ROW_NUMBER() OVER (PARTITION BY Department ORDER BY Salary) AS rn,
        COUNT(*) OVER (PARTITION BY Department) AS cnt
    FROM Employees
)
SELECT 
    Department,
    AVG(Salary) AS Median_Salary
FROM RankedSalaries
WHERE rn IN (FLOOR((cnt + 1) / 2), CEIL((cnt + 1) / 2))
GROUP BY Department;


-- Question 50
-- Find customers whose total order value is in the top 10% of all customers
WITH CustomerTotals AS (
    SELECT 
        Customer_ID,
        SUM(Total_Amount) AS Total_Order_Value
    FROM Orders
    GROUP BY Customer_ID
),
Ranked AS (
    SELECT 
        Customer_ID,
        Total_Order_Value,
        PERCENT_RANK() OVER (ORDER BY Total_Order_Value) AS pr
    FROM CustomerTotals
)
SELECT Customer_ID, Total_Order_Value
FROM Ranked
WHERE pr >= 0.9
ORDER BY Total_Order_Value DESC;















